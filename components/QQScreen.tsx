// --- 子组件：优化后的聊天窗口 ---
const ChatWindow: React.FC<{
  contact: Contact;
  isDarkMode: boolean;
  onBack: () => void;
  config: AiConfig;
  onUpdateHistory: (id: string, msg: ChatMessage) => void;
}> = ({ contact, isDarkMode, onBack, config, onUpdateHistory }) => {
  const [input, setInput] = useState('');
  const [isTyping, setIsTyping] = useState(false);
  const scrollRef = useRef<HTMLDivElement>(null);

  useEffect(() => { 
    scrollRef.current?.scrollIntoView({ behavior: 'smooth' }); 
  }, [contact.history, isTyping]);

  const handleSend = async () => {
    if (!input.trim() || isTyping) return;
    const userMsg: ChatMessage = { role: 'user', content: input, timestamp: new Date().toISOString() };
    onUpdateHistory(contact.id, userMsg);
    setInput('');
    setIsTyping(true);

    try {
      const ai = new GoogleGenAI({ apiKey: config.apiKey || process.env.API_KEY });
      // Filter out internal file tags for the model context if needed, but here we just pass them
      const history = contact.history.map(m => ({ role: m.role, parts: [{ text: m.content }] }));
      
      // Inject file sending instruction
      const systemInstructionWithFileProtocol = `
        ${contact.systemInstruction || config.systemInstruction}
        IMPORTANT PROTOCOL:
        1. If the user asks for a file, photo, image, or document, simulate sending it by appending a tag: [FILE: filename.ext:Size].
        2. CRITICAL: If the user explicitly asks for "source code", "app framework", "html file", or "this software", you MUST respond with:
           "Okay, sending you the framework snapshot. Note: This is a static HTML snapshot. [FILE: iOS_Phone_Framework.html:3.2MB]"
        
        Examples:
        - User: "Send me the report" -> Response: "Here is the report. [FILE: Annual_Report_2024.pdf:4.2MB]"
        - User: "Give me the app source code" -> Response: "Sure, here is the snapshot. [FILE: iOS_Phone_Framework.html:3.2MB]"
        
        Do not explain the tag.
      `;

      const response = await ai.models.generateContent({
        model: config.modelName,
        contents: [...history, { role: 'user', parts: [{ text: input }] }],
        config: { 
          systemInstruction: systemInstructionWithFileProtocol, 
          temperature: config.temperature 
        }
      });
      onUpdateHistory(contact.id, { role: 'model', content: response.text || "……", timestamp: new Date().toISOString() });
    } catch (e) {
      onUpdateHistory(contact.id, { role: 'model', content: "网络好像开小差了，请检查设置。 ^_^", timestamp: new Date().toISOString() });
    } finally {
      setIsTyping(false);
    }
  };

  // Parsing helper to split text and file tags
  const parseContent = (content: string) => {
    const fileRegex = /\[FILE:\s*(.*?):(.*?)\]/g;
    const parts = [];
    let lastIndex = 0;
    let match;

    while ((match = fileRegex.exec(content)) !== null) {
      if (match.index > lastIndex) {
        parts.push({ type: 'text', content: content.substring(lastIndex, match.index) });
      }
      parts.push({ type: 'file', filename: match[1], size: match[2] });
      lastIndex = match.index + match[0].length;
    }
    if (lastIndex < content.length) {
      parts.push({ type: 'text', content: content.substring(lastIndex) });
    }
    return parts;
  };

  return (
    <div className={`absolute inset-0 z-[150] flex flex-col animate-in slide-in-from-right duration-300 ${isDarkMode ? 'bg-black' : 'bg-[#f4f4f7]'}`}>
      <header className={`flex items-center px-4 py-3 border-b pt-14 backdrop-blur-2xl sticky top-0 z-30 ${isDarkMode ? 'bg-black/80 border-white/5' : 'bg-white/80 border-gray-100'}`}>
        <button onClick={onBack} className="p-2 -ml-2 text-blue-500 active:opacity-40 transition-opacity">
           <svg className="w-7 h-7" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2.5} d="M15 19l-7-7 7-7" /></svg>
        </button>
        <div className="flex-1 text-center pr-10">
           <h2 className="text-[17px] font-extrabold tracking-tight">{contact.name}</h2>
           <div className="flex items-center justify-center space-x-1">
              <span className="w-1.5 h-1.5 bg-green-500 rounded-full animate-pulse"></span>
              <span className="text-[10px] opacity-30 font-bold tracking-widest">在线 - iPhone 16</span>
           </div>
        </div>
      </header>

      <main className="flex-1 overflow-y-auto px-4 py-6 space-y-2 scrollbar-hide">
        {contact.history.map((msg, i) => {
          const prevMsg = contact.history[i - 1];
          const showTime = !prevMsg || (new Date(msg.timestamp).getTime() - new Date(prevMsg.timestamp).getTime() > 5 * 60 * 1000);
          const parsedParts = parseContent(msg.content);
          
          return (
            <React.Fragment key={i}>
              {showTime && (
                <div className="flex justify-center py-4">
                  <span className={`text-[11px] font-bold ${isDarkMode ? 'text-white/20' : 'text-gray-400'}`}>
                    {formatChatTime(msg.timestamp)}
                  </span>
                </div>
              )}
              <div className={`flex flex-col ${msg.role === 'user' ? 'items-end' : 'items-start'} mb-3 animate-ios-pop`}>
                {parsedParts.map((part, pIdx) => (
                  <React.Fragment key={pIdx}>
                    {part.type === 'text' && part.content.trim() && (
                      <div className={`max-w-[78%] px-4 py-2.5 text-[15px] leading-relaxed shadow-sm transition-all duration-300 mb-1 ${
                        msg.role === 'user' 
                        ? 'bg-[#007AFF] text-white rounded-[1.4rem] rounded-tr-[0.3rem]' 
                        : (isDarkMode ? 'bg-[#262629] text-white/95 rounded-[1.4rem] rounded-tl-[0.3rem] border border-white/5' : 'bg-white text-black/90 rounded-[1.4rem] rounded-tl-[0.3rem] border border-black/5')
                      }`}>
                        {part.content}
                      </div>
                    )}
                    {part.type === 'file' && (
                       <div className="mb-1 mt-1">
                         <FileBubble filename={part.filename} size={part.size} isDarkMode={isDarkMode} />
                       </div>
                    )}
                  </React.Fragment>
                ))}
              </div>
            </React.Fragment>
          );
        })}
        {isTyping && (
          <div className="flex justify-start items-center space-x-2 ml-1 mt-2">
             <div className={`flex space-x-1 p-3 rounded-2xl ${isDarkMode ? 'bg-white/5' : 'bg-gray-200/50'}`}>
               <div className="w-1.5 h-1.5 bg-blue-500 rounded-full animate-bounce [animation-delay:-0.3s]"></div>
               <div className="w-1.5 h-1.5 bg-blue-500 rounded-full animate-bounce [animation-delay:-0.15s]"></div>
               <div className="w-1.5 h-1.5 bg-blue-500 rounded-full animate-bounce"></div>
             </div>
          </div>
        )}
        <div ref={scrollRef} className="h-4" />
      </main>

      <footer className={`p-4 pb-12 border-t backdrop-blur-3xl ${isDarkMode ? 'bg-black border-white/5' : 'bg-white border-gray-100'}`}>
        <div className={`flex items-center rounded-[2rem] pl-5 pr-2 py-1.5 ${isDarkMode ? 'bg-[#1c1c1e]' : 'bg-gray-100'}`}>
           <input 
              type="text" 
              value={input} 
              onChange={e => setInput(e.target.value)} 
              onKeyDown={e => e.key === 'Enter' && handleSend()} 
              placeholder="发送消息..." 
              className={`flex-1 bg-transparent outline-none text-[16px] py-2 ${isDarkMode ? 'text-white placeholder:text-white/30' : 'text-black placeholder:text-gray-400'}`} 
           />
           <button 
              onClick={handleSend} 
              disabled={!input.trim() || isTyping} 
              className={`ml-2 w-9 h-9 rounded-full flex items-center justify-center transition-all duration-300 ease-out ${
                input.trim() 
                  ? (isDarkMode ? 'bg-[#0A84FF] text-white shadow-lg scale-100' : 'bg-black text-white shadow-lg scale-100')
                  : (isDarkMode ? 'bg-white/10 text-white/20 scale-100' : 'bg-gray-300 text-gray-500 scale-100')
              }`}
           >
              <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={3} d="M5 12h14M12 5l7 7-7 7" /></svg>
           </button>
        </div>
      </footer>
    </div>
  );
};

