// --- 工具函数：时间格式化 ---
const formatListTime = (isoString: string) => {
  const date = new Date(isoString);
  const now = new Date();
  const diff = now.getTime() - date.getTime();
  const oneDay = 24 * 60 * 60 * 1000;

  if (diff < oneDay && now.getDate() === date.getDate()) {
    return date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false });
  } else if (diff < oneDay * 2) {
    return '昨天';
  } else {
    return date.toLocaleDateString([], { month: 'numeric', day: 'numeric' });
  }
};

const formatChatTime = (isoString: string) => {
  const date = new Date(isoString);
  const now = new Date();
  
  if (now.toDateString() === date.toDateString()) {
    return date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false });
  } 
  return `${date.getMonth() + 1}月${date.getDate()}日 ${date.getHours().toString().padStart(2, '0')}:${date.getMinutes().toString().padStart(2, '0')}`;
};

// --- 子组件：文件消息气泡 ---
const FileBubble: React.FC<{ 
  filename: string; 
  size: string; 
  isDarkMode: boolean; 
}> = ({ filename, size, isDarkMode }) => {
  const [status, setStatus] = useState<'idle' | 'downloading' | 'completed'>('idle');
  const [progress, setProgress] = useState(0);

  const getIcon = (name: string) => {
    const ext = name.split('.').pop()?.toLowerCase();
    if (['jpg', 'png', 'jpeg', 'gif'].includes(ext || '')) return '🖼️';
    if (['pdf', 'doc', 'docx'].includes(ext || '')) return '📄';
    if (['zip', 'rar', 'html', 'tsx', 'ts'].includes(ext || '')) return '📦';
    return '📑';
  };

  const handleDownload = () => {
    if (status !== 'idle') return;
    setStatus('downloading');
    let p = 0;
    const interval = setInterval(() => {
      p += Math.random() * 15;
      if (p >= 100) {
        p = 100;
        clearInterval(interval);
        setStatus('completed');
        
        // --- 真实下载触发逻辑 (优化版) ---
        const isSourceCode = filename.includes('Framework') || filename.includes('.html') || filename.includes('Source');
        let content = '';
        let mimeType = 'text/plain';

        if (isSourceCode) {
           // 克隆当前文档以便修改
           const docClone = document.documentElement.cloneNode(true) as HTMLElement;
           
           // 1. 移除本地运行会报错的脚本 (如 /index.tsx)
           const scripts = docClone.querySelectorAll('script');
           scripts.forEach(s => {
             // 移除所有指向根目录的 module 脚本，或者 vite注入的脚本
             if (s.src && (s.src.includes('localhost') || s.src.startsWith('/') || s.getAttribute('src')?.startsWith('/'))) {
               s.remove();
             }
           });

           // 2. 注入一个提示横幅，告知用户这是静态快照
           const bannerDiv = document.createElement('div');
           bannerDiv.innerHTML = `
             <div style="
               position: fixed; top: 0; left: 0; right: 0; z-index: 99999;
               background: rgba(0, 0, 0, 0.85); color: white;
               padding: 12px; text-align: center;
               font-family: -apple-system, sans-serif; backdrop-filter: blur(10px);
               border-bottom: 1px solid rgba(255,255,255,0.1);
             ">
               <div style="font-weight: bold; font-size: 14px;">⚠️ Static Snapshot Mode</div>
               <div style="font-size: 11px; opacity: 0.7; margin-top: 2px;">
                 Interactive features (AI Chat, Navigation) require a React build environment.
               </div>
             </div>
             <style>body { padding-top: 50px !important; }</style>
           `;
           docClone.querySelector('body')?.prepend(bannerDiv);

           content = `<!DOCTYPE html>\n<!-- Generated by iOS AI Framework -->\n` + docClone.outerHTML;
           mimeType = 'text/html';
        } else {
           content = `This is a simulated file content for: ${filename}\nSize: ${size}\nTimestamp: ${new Date().toISOString()}`;
        }

        const blob = new Blob([content], { type: mimeType });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
        // -----------------------
      }
      setProgress(p);
    }, 150);
  };

  return (
    <div 
      onClick={handleDownload}
      className={`relative overflow-hidden group cursor-pointer select-none transition-all duration-300 ${
        status === 'completed' ? 'opacity-80' : 'active:scale-95'
      } ${isDarkMode ? 'bg-[#262629] border border-white/10' : 'bg-white border border-gray-100'} rounded-2xl p-3 flex items-center space-x-3 min-w-[200px] max-w-[260px]`}
    >
      {/* 进度条背景 */}
      {status === 'downloading' && (
        <div 
          className="absolute inset-0 bg-blue-500/10 transition-all duration-150 ease-linear" 
          style={{ width: `${progress}%` }}
        />
      )}

      {/* 图标区域 */}
      <div className={`w-12 h-12 rounded-xl flex items-center justify-center text-2xl shadow-sm z-10 transition-colors ${
        status === 'completed' 
          ? 'bg-green-500 text-white' 
          : (isDarkMode ? 'bg-white/10' : 'bg-gray-100')
      }`}>
        {status === 'completed' ? (
          <svg className="w-6 h-6 animate-in zoom-in" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={3} d="M5 13l4 4L19 7" /></svg>
        ) : getIcon(filename)}
      </div>

      {/* 文本区域 */}
      <div className="flex-1 min-w-0 z-10">
        <div className={`text-[14px] font-bold truncate ${isDarkMode ? 'text-white' : 'text-black'}`}>
          {filename}
        </div>
        <div className={`text-[11px] font-medium flex justify-between items-center ${isDarkMode ? 'text-white/40' : 'text-black/40'}`}>
          <span>{status === 'completed' ? '已保存' : size}</span>
          {status === 'idle' && <span className="text-blue-500">获取</span>}
          {status === 'downloading' && <span className="text-blue-500">{Math.round(progress)}%</span>}
        </div>
      </div>
    </div>
  );
};

